#!/usr/bin/env node
/* scripts/add-provider.mjs
 *
 * Scaffolds a new cloud provider across every file that has to know about it.
 * Nothing is written until all the edits succeed, so a missing anchor leaves
 * the repository untouched.
 *
 *   node scripts/add-provider.mjs --id oracle --name "Oracle Cloud" \
 *     --namespace oracle/oci --prefix oci- --color text-red-600 \
 *     --docs https://docs.oracle.com/en-us/iaas/ \
 *     --console https://cloud.oracle.com/ \
 *     --pricing https://www.oracle.com/cloud/price-list/
 *
 *   node scripts/add-provider.mjs --id oracle ... --dry-run
 */

import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib/load-ts.mjs';

const args = process.argv.slice(2);
const option = (name, fallback = null) => {
  const index = args.indexOf(`--${name}`);
  return index === -1 ? fallback : args[index + 1];
};
const flag = (name) => args.includes(`--${name}`);

const id = option('id');
const name = option('name');

if (!id || !name) {
  console.error(
    'Usage: node scripts/add-provider.mjs --id <id> --name "<Display name>" [--namespace <tf-namespace>] [--prefix <id-prefix>] [--color <tailwind-class>] [--docs <url>] [--console <url>] [--pricing <url>] [--shell <url>] [--dry-run]'
  );
  process.exit(1);
}

if (!/^[a-z][a-z0-9]*$/.test(id)) {
  console.error('The provider id must be lowercase alphanumeric (e.g. "oracle").');
  process.exit(1);
}

const config = {
  id,
  name,
  component: id.charAt(0).toUpperCase() + id.slice(1),
  namespace: option('namespace', `${id}/${id}`),
  prefix: option('prefix', `${id}-`),
  color: option('color', 'text-slate-500'),
  docs: option('docs', `https://docs.${id}.com/`),
  console: option('console', `https://console.${id}.com/`),
  pricing: option('pricing', `https://www.${id}.com/pricing/`),
  shell: option('shell', option('console', `https://console.${id}.com/`)),
};

const edits = [];

function patch(relativePath, replacements) {
  const filePath = path.join(ROOT, relativePath);
  let source = fs.readFileSync(filePath, 'utf8');

  if (source.includes(`'${config.id}'`) && relativePath !== 'src/lib/data-audit.ts') {
    throw new Error(`${relativePath} already mentions "${config.id}".`);
  }

  for (const [anchor, replacement] of replacements) {
    if (!source.includes(anchor)) {
      throw new Error(`Anchor not found in ${relativePath}:\n${anchor}`);
    }
    source = source.replace(anchor, replacement);
  }

  edits.push({ filePath, source, relativePath });
}

function create(relativePath, content) {
  const filePath = path.join(ROOT, relativePath);
  if (fs.existsSync(filePath)) {
    throw new Error(`${relativePath} already exists.`);
  }
  edits.push({ filePath, source: content, relativePath, created: true });
}

